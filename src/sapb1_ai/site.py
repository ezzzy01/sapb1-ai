"""Writes the chat site's proxy config (./company.sh site / start / stop).

  site/caddy/Caddyfile               port 3100: login page, then each signed-in person to their company's own chat
                                     service only: chat page (/sapb1/chat), dashboard (/sapb1/home), Excel downloads
  site/docker-compose.companies.yml  kept for the old Open WebUI data volumes (Open WebUI is switched off; its chats
                                     stay in those volumes)
Both are generated from companies/*/company.env and git-ignored (they hold company names).
"""

import json
import sys
from pathlib import Path

from dotenv import dotenv_values

from .portal import ROOT, SITE_DIR, companies

CADDY_DIR = SITE_DIR / "caddy"
COMPOSE = SITE_DIR / "docker-compose.companies.yml"
PORTAL = "host.docker.internal:8090"
HEADERS = ("X-Sapb1-Email", "X-Sapb1-Name", "X-Sapb1-Role", "X-Sapb1-Company", "X-Sapb1-Groups")


def container(cid: str) -> str:
    return f"sapb1-ai-webui-{cid}"


def agent_port(cid: str) -> str:
    return dotenv_values(ROOT / "companies" / cid / "company.env").get("AGENT_PORT") or ""


def caddyfile(ids: list[str]) -> str:
    strip = "\n".join(f"\t\trequest_header -{h}" for h in HEADERS)

    def route(c: str) -> str:
        # Everything comes from the company's own chat service (agent.py); any other address (old Open WebUI links,
        # the bare site) goes to the chat page.
        port = agent_port(c)
        if not port:
            return (f"\t\t@{c} header X-Sapb1-Company {c}\n\t\thandle @{c} {{\n"
                    f"\t\t\trespond \"This company's chat is not set up.\" 503\n\t\t}}")
        return (f"\t\t@{c} header X-Sapb1-Company {c}\n\t\thandle @{c} {{\n"
                f"\t\t\t@agent_{c} path /sapb1/home* /sapb1/chat* /static/exports/*\n"
                f"\t\t\thandle @agent_{c} {{\n\t\t\t\trequest_body {{\n\t\t\t\t\tmax_size 12MB\n\t\t\t\t}}\n"
                f"\t\t\t\treverse_proxy host.docker.internal:{port}\n\t\t\t}}\n"
                f"\t\t\thandle {{\n\t\t\t\tredir * /sapb1/chat 302\n\t\t\t}}\n\t\t}}")
    routes = "\n".join(route(c) for c in ids)
    return f"""# Generated by ./company.sh site (src/sapb1_ai/site.py). Do not edit.
{{
	auto_https off
}}

:3100 {{
	# The chat page and the dashboard change with updates: browsers (phones especially) must check for a newer copy
	# each time instead of keeping an old one.
	header /sapb1/home ?Cache-Control "no-cache"
	header /sapb1/chat ?Cache-Control "no-cache"
	route {{
		# Identity comes only from the login service, never from the browser.
{strip}
		handle /portal/* {{
			reverse_proxy {PORTAL}
		}}
		forward_auth {PORTAL} {{
			uri /portal/verify
			copy_headers {" ".join(HEADERS)}
		}}
		# Each person reaches only the company chosen at sign-in.
{routes}
		respond "This company is not available." 403
	}}
}}
"""


def compose(cos: dict[str, str]) -> dict:
    """Open WebUI is switched off (our own chat page replaced it). Its data volumes stay declared so the old chats are
    kept (docker volume sapb1-ai_webui-<company>)."""
    return {"volumes": {f"webui-{cid}": {} for cid in cos}}


def build() -> list[str]:
    cos = companies()
    CADDY_DIR.mkdir(parents=True, exist_ok=True)
    for cid in cos:
        (ROOT / "exports" / cid).mkdir(parents=True, exist_ok=True)
    (CADDY_DIR / "Caddyfile").write_text(caddyfile(list(cos)))
    COMPOSE.write_text("# Generated by ./company.sh site (src/sapb1_ai/site.py). Do not edit.\n" + json.dumps(compose(cos), indent=1))
    return list(cos)


if __name__ == "__main__":
    if sys.argv[1:] == ["build"]:
        print(" ".join(build()))
    else:
        sys.exit("usage: python -m sapb1_ai.site build")
