"""Writes the chat site's proxy config and one Open WebUI per started company (./company.sh site / start / stop).

  site/caddy/Caddyfile               port 3100: login page, then each signed-in person to their company's site only
  site/docker-compose.companies.yml  one Open WebUI per company: own container, database (chats, accounts, files),
                                     network shared only with the proxy, and that company's Excel downloads only
Both are generated from companies/*/company.env and git-ignored (they hold company names).
"""

import json
import sys
from pathlib import Path

from .portal import ROOT, SITE_DIR, companies

CADDY_DIR = SITE_DIR / "caddy"
COMPOSE = SITE_DIR / "docker-compose.companies.yml"
PORTAL = "host.docker.internal:8090"
HEADERS = ("X-Sapb1-Email", "X-Sapb1-Name", "X-Sapb1-Role", "X-Sapb1-Company", "X-Sapb1-Groups")


def container(cid: str) -> str:
    return f"sapb1-ai-webui-{cid}"


def caddyfile(ids: list[str]) -> str:
    strip = "\n".join(f"\t\trequest_header -{h}" for h in HEADERS)
    routes = "\n".join(f"\t\t@{c} header X-Sapb1-Company {c}\n\t\thandle @{c} {{\n\t\t\treverse_proxy {container(c)}:8080\n\t\t}}"
                       for c in ids)
    return f"""# Generated by ./company.sh site (src/sapb1_ai/site.py). Do not edit.
{{
	auto_https off
}}

:3100 {{
	route {{
		# Identity comes only from the login service, never from the browser.
{strip}
		handle /portal/* {{
			reverse_proxy {PORTAL}
		}}
		# Open WebUI's own sign-out button ends the shared sign-in.
		handle /api/v1/auths/signout {{
			rewrite * /portal/logout?api=1
			reverse_proxy {PORTAL}
		}}
		forward_auth {PORTAL} {{
			uri /portal/verify
			copy_headers {" ".join(HEADERS)}
		}}
		# Each person reaches only the company chosen at sign-in.
{routes}
		respond "This company is not available." 403
	}}
}}
"""


def compose(cos: dict[str, str]) -> dict:
    services, networks, volumes = {}, {}, {}
    for cid, name in cos.items():
        net = f"site-{cid}"
        services[f"webui-{cid}"] = {
            "image": "ghcr.io/open-webui/open-webui:main",
            "container_name": container(cid),
            "restart": "unless-stopped",
            "extra_hosts": ["host.docker.internal:host-gateway"],
            "networks": [net],
            "environment": {
                "WEBUI_NAME": f"{name} · SAP B1 AI",
                # Sign-in is done by the login service in front (src/sapb1_ai/portal.py); the proxy adds these headers.
                "WEBUI_AUTH_TRUSTED_EMAIL_HEADER": "X-Sapb1-Email",
                "WEBUI_AUTH_TRUSTED_NAME_HEADER": "X-Sapb1-Name",
                "WEBUI_AUTH_TRUSTED_ROLE_HEADER": "X-Sapb1-Role",
                "WEBUI_AUTH_TRUSTED_GROUPS_HEADER": "X-Sapb1-Groups",
                "DEFAULT_USER_ROLE": "user",
                # Only this company's chat service (set by ./company.sh); no direct model or internet access.
                "ENABLE_OLLAMA_API": "false",
                "ENABLE_WEB_SEARCH": "false",
                # Privacy: chats stay with the person who wrote them.
                "ENABLE_ADMIN_CHAT_ACCESS": "false",
                "ENABLE_ADMIN_EXPORT": "false",
                "ENABLE_COMMUNITY_SHARING": "false",
                "ENABLE_VERSION_UPDATE_CHECK": "false",
                "SCARF_NO_ANALYTICS": "true",
                "DO_NOT_TRACK": "true",
                "ANONYMIZED_TELEMETRY": "false",
            },
            "volumes": [
                f"webui-{cid}:/app/backend/data",
                # Fiori Horizon theme and the small page script (webui/); edits apply on browser refresh.
                "./webui/custom.css:/app/build/static/custom.css:ro",
                "./webui/loader.js:/app/build/static/loader.js:ro",
                "./webui/fiori.css:/app/backend/open_webui/static/sapb1/fiori.css:ro",
                # This company's Excel downloads only (src/sapb1_ai/export.py).
                f"./exports/{cid}:/app/backend/open_webui/static/exports/{cid}:ro",
            ],
        }
        networks[net] = {}
        volumes[f"webui-{cid}"] = {}
    # The proxy joins every company's network; the company sites cannot reach each other.
    services["proxy"] = {"networks": list(networks)}
    return {"services": services, "networks": networks, "volumes": volumes}


def build() -> list[str]:
    cos = companies()
    CADDY_DIR.mkdir(parents=True, exist_ok=True)
    for cid in cos:
        (ROOT / "exports" / cid).mkdir(parents=True, exist_ok=True)
    (CADDY_DIR / "Caddyfile").write_text(caddyfile(list(cos)))
    COMPOSE.write_text("# Generated by ./company.sh site (src/sapb1_ai/site.py). Do not edit.\n" + json.dumps(compose(cos), indent=1))
    return list(cos)


if __name__ == "__main__":
    if sys.argv[1:] == ["build"]:
        print(" ".join(build()))
    else:
        sys.exit("usage: python -m sapb1_ai.site build")
